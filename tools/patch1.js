const fs = require("fs");
const P = "android/assets/www/index.html";
let h = fs.readFileSync(P, "utf8");

const start = h.indexOf("// ========== 加载云端 ==========");
const end = h.indexOf("// ========== 视图切换 ==========");
if (start < 0 || end < 0) throw new Error("定位失败: " + start + "," + end);

const repl = [
"// ========== 本地加载 ==========",
"async function loadFromCloud() {",
"  try {",
"    const root = loadAllLocal();",
"    const members = root.members || [];",
"    if (members.length === 0) {",
"      return { ok: false, empty: true };",
"    }",
"    data.members = members.map(m => {",
"      const recs = normalizeRecords(m.records);",
"      const mm = { id: m.id, name: m.name, totalScore: 0, records: recs };",
"      mm.totalScore = recomputeTotal(mm);",
"      return mm;",
"    });",
"    saveCache();",
"    return { ok: true, empty: false };",
"  } catch (e) {",
"    console.warn('读取本地数据失败', e);",
"    return { ok: false, empty: false, reason: 'local_fail', error: e };",
"  }",
"}",
"",
"// ========== 本地保存（写 SQLite） ==========",
"async function saveToCloud() {",
"  const statusEl = document.getElementById('syncStatus');",
"",
"  if (data.members.length === 0) {",
"    if (statusEl) { statusEl.textContent = '无成员'; statusEl.className = 'status-msg'; }",
"    return;",
"  }",
"",
"  if (statusEl) { statusEl.textContent = '保存中...'; statusEl.className = 'status-msg'; }",
"  try {",
"    const payload = {",
"      members: data.members.map(m => ({",
"        id: m.id,",
"        name: m.name,",
"        records: m.records",
"      }))",
"    };",
"    const ok = nativeCall('replaceAll', [JSON.stringify(payload)], false);",
"    if (!ok && hasNative) throw new Error('写入失败');",
"    saveCache();",
"    if (statusEl) {",
"      statusEl.textContent = '已保存';",
"      statusEl.className = 'status-msg success';",
"      setTimeout(() => { statusEl.textContent = ''; statusEl.className = 'status-msg'; }, 1800);",
"    }",
"  } catch (e) {",
"    if (statusEl) {",
"      statusEl.textContent = '保存失败：' + e.message;",
"      statusEl.className = 'status-msg error';",
"    }",
"    throw e;",
"  }",
"}",
"",
"async function uploadPassword(newPwd) {",
"  const ok = nativeCall('changePassword', [String(newPwd)], false);",
"  if (!ok) throw new Error('密码保存失败');",
"}",
"",
"let syncTimer;",
"function autoSync() {",
"  clearTimeout(syncTimer);",
"  syncTimer = setTimeout(() => {",
"    saveToCloud().catch(e => console.warn('本地保存失败', e));",
"  }, 400);",
"}",
"",
""].join("\n");

h = h.slice(0, start) + repl + h.slice(end);
fs.writeFileSync(P, h);
console.log("已替换 loadFromCloud/saveToCloud/autoSync，长度", repl.length);
